import { useState } from "react";
import { Button, Card, Chip } from "@mui/material";
import { CallSplit, OpenInNew, StarBorder } from "@mui/icons-material";
import { FiGithub } from "react-icons/fi";
import type { GithubRepo } from "../../types/github";
import { GITHUB_USERNAME } from "../../data/portfolio";

// make sure the live link always has https://
const toUrl = (link: string) => (link.startsWith("http") ? link : `https://${link}`);

const ProjectCard = ({ repo }: { repo: GithubRepo }) => {
  const [imageFailed, setImageFailed] = useState(false);
  const liveUrl = repo.homepage ? toUrl(repo.homepage) : null;
  // preview image generated by GitHub for this repository
  const imageUrl = `https://opengraph.githubassets.com/1/${GITHUB_USERNAME}/${repo.name}`;

  return (
    <Card
      elevation={0}
      className="flex h-full flex-col overflow-hidden !rounded-[2rem] !bg-white transition duration-300 hover:-translate-y-1 hover:shadow-xl"
    >
      {!imageFailed && (
        <img
          src={imageUrl}
          alt={`${repo.name} preview`}
          loading="lazy"
          onError={() => setImageFailed(true)}
          className="h-44 w-full object-cover"
        />
      )}

      <div className="flex grow flex-col p-6 text-navy">
        <h3 className="m-0 text-lg font-bold break-words">{repo.name}</h3>
        <p className="m-0 mt-2 grow text-sm text-slate-600">{repo.description ?? "No description provided."}</p>

        <div className="mt-4 flex flex-wrap items-center gap-3 text-sm">
          {repo.language && <Chip label={repo.language} size="small" className="!bg-navy !text-leaf" />}
          <span className="flex items-center gap-1" aria-label={`${repo.stargazers_count} stars`}>
            <StarBorder fontSize="small" /> {repo.stargazers_count}
          </span>
          <span className="flex items-center gap-1" aria-label={`${repo.forks_count} forks`}>
            <CallSplit fontSize="small" /> {repo.forks_count}
          </span>
        </div>

        <p className="m-0 mt-3 text-xs text-slate-500">
          Updated {new Date(repo.updated_at).toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric" })}
        </p>

        <div className="mt-4 flex flex-wrap gap-2">
          {liveUrl && (
            <Button variant="contained" size="small" href={liveUrl} target="_blank" rel="noopener noreferrer" endIcon={<OpenInNew />}>
              Live Demo
            </Button>
          )}
          <Button variant="outlined" size="small" href={repo.html_url} target="_blank" rel="noopener noreferrer" startIcon={<FiGithub />}>
            GitHub
          </Button>
        </div>
      </div>
    </Card>
  );
};

export default ProjectCard;
